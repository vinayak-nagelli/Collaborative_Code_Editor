async function createNode(projectId, userId, node, parentId, parentPath) {
  const path = parentPath ? `${parentPath}/${node.name}` : node.name;

  const doc = await File.create({
    projectId,
    parentId,
    name: node.name,
    type: node.isFolder ? "folder" : "file",
    path,
    content: node.isFolder ? "" : node.content || "",
    language: node.isFolder ? "plaintext" : languageFor(node.name),
    createdBy: userId,
    lastEditedBy: userId,
  });

  if (node.isFolder && Array.isArray(node.children)) {
    for (const child of node.children) {
      await createNode(projectId, userId, child, doc._id, path);
    }
  }

  return doc;
}

export const seedTemplate = async (projectId, userId, templateKey) => {
  const nodes = TEMPLATES[templateKey] || TEMPLATES.empty;
  for (const node of nodes) {
    await createNode(projectId, userId, node, null, "");
  }
};
